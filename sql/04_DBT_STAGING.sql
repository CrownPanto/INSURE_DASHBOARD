-- ─────────────────────────────────────────────
-- STG_ASSET_INCOME: GRANDATA.ASSET_INCOME_INFO 정규화
-- 핵심 팩트 테이블 - 115개 컬럼 중 INSURE 관련 40+개 선별
-- ─────────────────────────────────────────────
CREATE OR REPLACE VIEW STG_ASSET_INCOME AS
SELECT
    -- 키
    DISTRICT_CODE,
    STANDARD_YEAR_MONTH                          AS YEAR_MONTH,
    GENDER,
    AGE_GROUP,
    -- 인구
    CUSTOMER_COUNT,
    -- 소득 분포 (7개 구간)
    MEDIAN_INCOME,
    RATE_INCOME_UNDER_10M,
    RATE_INCOME_10M_TO_20M,
    RATE_INCOME_20M_TO_30M,
    RATE_INCOME_30M_TO_40M,
    RATE_INCOME_40M_TO_50M,
    RATE_INCOME_50M_TO_70M,
    RATE_INCOME_OVER_70M,
    -- 직업 분포 (7개 그룹)
    RATE_MODEL_GROUP_LARGE_COMPANY_EMPLOYEE,
    RATE_MODEL_GROUP_GENERAL_EMPLOYEE,
    RATE_MODEL_GROUP_PROFESSIONAL,
    RATE_MODEL_GROUP_FIELD_WORK,
    RATE_MODEL_GROUP_SME,
    RATE_MODEL_GROUP_OTHERS,
    -- 신용 점수
    AVERAGE_SCORE                                AS CREDIT_SCORE_AVG,
    RATE_SCORE1                                  AS CREDIT_HIGH_RATE,
    RATE_SCORE2                                  AS CREDIT_MID_RATE,
    RATE_SCORE3                                  AS CREDIT_LOW_RATE,
    -- 연체 정보
    DELINQUENT_1D_COUNT,
    DELINQUENT_90_COUNT,
    AVERAGE_DELINQUENT_AMOUNT,
    -- 자산/주택
    AVERAGE_ASSET_AMOUNT,
    OWN_HOUSING_COUNT,
    MULTIPLE_HOUSING_COUNT,
    -- 주거 규모
    PYEONG_UNDER_20_COUNT                        AS SMALL_UNIT_COUNT,
    PYEONG_20_TO_40_COUNT                        AS MID_UNIT_COUNT,
    PYEONG_40_TO_60_COUNT                        AS LARGE_UNIT_COUNT,
    PYEONG_OVER_60_COUNT                         AS LUXURY_UNIT_COUNT,
    -- 대출
    BALANCE_COUNT,
    MORTGAGE1_BALANCE_COUNT,
    MORTGAGE2_BALANCE_COUNT,
    HOUSING_BALANCE_COUNT,
    -- 카드 사용
    TOTAL_USAGE_AMOUNT,
    AVERAGE_FULL_PAYMENT_USAGE_AMOUNT            AS FULL_PAY_AMOUNT,
    AVERAGE_INSTALLMENT_USAGE_AMOUNT             AS INSTALLMENT_AMOUNT,
    AVERAGE_ABROAD_AMOUNT                        AS ABROAD_SPEND_AMOUNT,
    -- 고소득
    RATE_HIGH_END
FROM SEOUL_DISTRICTLEVEL_DATA_FLOATING_POPULATION_CONSUMPTION_AND_ASSETS.GRANDATA.ASSET_INCOME_INFO;

