-- ─────────────────────────────────────────────
-- STG_APT_PRICE: 아파트 시세 (RICHGO)
-- ─────────────────────────────────────────────
CREATE OR REPLACE VIEW STG_APT_PRICE AS
SELECT
    BJD_CODE,
    SD,
    SGG,
    EMD,
    TOTAL_HOUSEHOLDS,
    YYYYMMDD,
    LEFT(YYYYMMDD::VARCHAR, 6)                   AS YEAR_MONTH,
    MEME_PRICE_PER_SUPPLY_PYEONG                 AS SALE_PRICE_PER_PYEONG,
    JEONSE_PRICE_PER_SUPPLY_PYEONG               AS JEONSE_PRICE_PER_PYEONG
FROM KOREAN_POPULATION__APARTMENT_MARKET_PRICE_DATA.HACKATHON_2025Q2.REGION_APT_RICHGO_MARKET_PRICE_M_H;

