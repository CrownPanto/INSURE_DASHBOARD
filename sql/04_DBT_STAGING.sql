-- ─────────────────────────────────────────────
-- STG_FLOATING_POP: 유동인구 정규화
-- ─────────────────────────────────────────────
CREATE OR REPLACE VIEW STG_FLOATING_POP AS
SELECT
    DISTRICT_CODE,
    STANDARD_YEAR_MONTH                          AS YEAR_MONTH,
    WEEKDAY_WEEKEND,
    GENDER,
    AGE_GROUP,
    TIME_SLOT,
    RESIDENTIAL_POPULATION,
    WORKING_POPULATION,
    VISITING_POPULATION,
    RESIDENTIAL_POPULATION + WORKING_POPULATION + VISITING_POPULATION AS TOTAL_POPULATION
FROM SEOUL_DISTRICTLEVEL_DATA_FLOATING_POPULATION_CONSUMPTION_AND_ASSETS.GRANDATA.FLOATING_POPULATION_INFO;

