USE DATABASE INSURE_DB;

-- RAG 스키마 생성
CREATE SCHEMA IF NOT EXISTS INSURE_DB.RAG;

-- RAG 청크 테이블
CREATE TABLE IF NOT EXISTS INSURE_DB.RAG.RAG_CHUNKS (
    CHUNK_ID VARCHAR(200) PRIMARY KEY,
    CONTEXT VARCHAR(500),
    CHUNK_TEXT VARCHAR(16000),
    INSURER VARCHAR(100),
    PRODUCT VARCHAR(200),
    CATEGORY VARCHAR(50),
    SECTION VARCHAR(200),
    CHAPTER VARCHAR(200),
    ARTICLE_NUMBER VARCHAR(50),
    ARTICLE_TITLE VARCHAR(200),
    CHAR_LEN INTEGER,
    APPROX_TOKENS INTEGER,
    DOMAIN_PRIORITY VARCHAR(20),
    SQL_REFERENCES ARRAY,
    CHUNK_EMBEDDING VECTOR(FLOAT, 768),
    CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

-- 확인
SELECT 'RAG_CHUNKS 테이블 생성 완료' AS STATUS;
DESC TABLE INSURE_DB.RAG.RAG_CHUNKS;
