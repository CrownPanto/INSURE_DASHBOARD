SELECT
    YEAR,
    QUARTER,
    ACCIDENT_TYPE,
    PRODUCT_DETAIL,
    ACCIDENT_COUNT,
    CAUSE_SUMMARY,
    -- Cortex LLM SENTIMENT (실행 시 주석 해제)
