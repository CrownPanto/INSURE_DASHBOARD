        WHEN CAUSE_SUMMARY LIKE '%사망%' OR CAUSE_SUMMARY LIKE '%열폭주%' THEN -0.9
        WHEN CAUSE_SUMMARY LIKE '%폭발%' OR CAUSE_SUMMARY LIKE '%감전%' THEN -0.7
