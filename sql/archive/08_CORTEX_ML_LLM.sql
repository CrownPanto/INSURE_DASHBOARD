        WHEN CAUSE_SUMMARY LIKE '%비정품%' OR CAUSE_SUMMARY LIKE '%미인증%' THEN '비인증제품'
        ELSE '기타'
    END AS ROOT_CAUSE_CATEGORY
FROM INSURE_DB.RAW_PUBLIC.CONSUMER_ACCIDENT;

