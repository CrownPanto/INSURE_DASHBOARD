-- 세그먼트 분류 검증용 뷰
CREATE OR REPLACE VIEW V_SEGMENT_VALIDATION AS
SELECT
    s.DISTRICT_CODE,
    s.YEAR_MONTH,
    s.SEGMENT_A,
    s.SEGMENT_B,
    s.SEGMENT_E,
    s.MEDIAN_INCOME,
    s.AVERAGE_ASSET_AMOUNT,
    s.CREDIT_SCORE_AVG,
    s.TOTAL_USAGE_AMOUNT,
    -- 세그먼트 간 일관성 검증
    CASE
        WHEN s.SEGMENT_B = 'B1_영리치' AND s.AVERAGE_ASSET_AMOUNT < 300000000 THEN '⚠️ 불일치: 영리치인데 자산 낮음'
        WHEN s.SEGMENT_E = 'E1_저위험안정' AND s.CREDIT_SCORE_AVG < 700 THEN '⚠️ 불일치: 저위험인데 신용 낮음'
        WHEN s.SEGMENT_B = 'B2_알뜰형' AND s.TOTAL_USAGE_AMOUNT > 2000000 THEN '⚠️ 불일치: 알뜰형인데 소비 높음'
        ELSE '✅ 일관성 확인'
    END AS CONSISTENCY_CHECK
FROM INSURE_DB.INTERMEDIATE.INT_SEGMENT_CLASSIFICATION s;


