        WHEN CAUSE_SUMMARY LIKE '%과열%' OR CAUSE_SUMMARY LIKE '%누출%' THEN -0.3
        ELSE -0.1
    END AS SEVERITY_SCORE_MANUAL,
    CASE
        WHEN CAUSE_SUMMARY LIKE '%노후%' OR CAUSE_SUMMARY LIKE '%10년%' OR CAUSE_SUMMARY LIKE '%5년%' THEN '노후제품'
        WHEN CAUSE_SUMMARY LIKE '%부주의%' OR CAUSE_SUMMARY LIKE '%미청소%' THEN '사용자부주의'
