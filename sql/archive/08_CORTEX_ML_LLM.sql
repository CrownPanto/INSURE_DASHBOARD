-- 대안: 수동 트렌드 기반 예측 뷰 (FORECAST 불가 시)
CREATE OR REPLACE VIEW V_FIRE_FORECAST_MANUAL AS
WITH yearly AS (
    SELECT
        DISTRICT_NAME,
        YEAR,
        SUM(TOTAL_FIRES) AS FIRES,
        SUM(BUILDING_FIRES) AS B_FIRES
    FROM INSURE_DB.RAW_PUBLIC.FIRE_STATS
    GROUP BY DISTRICT_NAME, YEAR
),
trend AS (
    SELECT
        DISTRICT_NAME,
        AVG(FIRES) AS AVG_FIRES,
        REGR_SLOPE(FIRES, YEAR) AS TREND_SLOPE,
        MAX(YEAR) AS LAST_YEAR
    FROM yearly
    GROUP BY DISTRICT_NAME
)
SELECT
    DISTRICT_NAME,
    2025 AS FORECAST_YEAR,
    ROUND(AVG_FIRES + TREND_SLOPE * (2025 - LAST_YEAR), 0) AS PREDICTED_FIRES,
    ROUND((AVG_FIRES + TREND_SLOPE * (2025 - LAST_YEAR)) * 0.85, 0) AS LOWER_95,
    ROUND((AVG_FIRES + TREND_SLOPE * (2025 - LAST_YEAR)) * 1.15, 0) AS UPPER_95,
    '추세기반예측' AS METHOD
FROM trend
UNION ALL
SELECT
    DISTRICT_NAME,
    2026 AS FORECAST_YEAR,
    ROUND(AVG_FIRES + TREND_SLOPE * (2026 - LAST_YEAR), 0),
    ROUND((AVG_FIRES + TREND_SLOPE * (2026 - LAST_YEAR)) * 0.82, 0),
    ROUND((AVG_FIRES + TREND_SLOPE * (2026 - LAST_YEAR)) * 1.18, 0),
    '추세기반예측'
FROM trend;


