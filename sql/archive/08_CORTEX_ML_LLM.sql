-- 대안: Z-score 기반 이상치 탐지
CREATE OR REPLACE VIEW V_TRANSACTION_ANOMALY_MANUAL AS
WITH stats AS (
    SELECT
        DISTRICT_NAME,
        AVG(TOTAL_TRANSACTIONS) AS MEAN_TX,
        STDDEV(TOTAL_TRANSACTIONS) AS STD_TX
    FROM INSURE_DB.RAW_PUBLIC.REAL_ESTATE_TRANSACTIONS
    GROUP BY DISTRICT_NAME
)
SELECT
    r.DISTRICT_NAME,
    r.YEAR_MONTH,
    r.TOTAL_TRANSACTIONS,
    s.MEAN_TX,
    s.STD_TX,
    ROUND((r.TOTAL_TRANSACTIONS - s.MEAN_TX) / NULLIF(s.STD_TX, 0), 2) AS Z_SCORE,
    CASE
        WHEN ABS((r.TOTAL_TRANSACTIONS - s.MEAN_TX) / NULLIF(s.STD_TX, 0)) > 2.0 THEN TRUE
        ELSE FALSE
    END AS IS_ANOMALY,
    CASE
        WHEN (r.TOTAL_TRANSACTIONS - s.MEAN_TX) / NULLIF(s.STD_TX, 0) > 2.0 THEN '급증_이사성수기'
        WHEN (r.TOTAL_TRANSACTIONS - s.MEAN_TX) / NULLIF(s.STD_TX, 0) < -2.0 THEN '급감_비수기'
        ELSE '정상범위'
    END AS ANOMALY_TYPE
FROM INSURE_DB.RAW_PUBLIC.REAL_ESTATE_TRANSACTIONS r
JOIN stats s ON r.DISTRICT_NAME = s.DISTRICT_NAME;


