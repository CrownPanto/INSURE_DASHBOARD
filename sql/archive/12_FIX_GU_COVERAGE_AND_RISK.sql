USE SCHEMA INTERMEDIATE;

-- Step 1: Rebuild INT_DISTRICT_RISK_SCORE with adjusted thresholds
CREATE OR REPLACE TABLE INT_DISTRICT_RISK_SCORE AS
WITH fire_risk AS (
    SELECT DISTRICT_NAME, YEAR, SUM(TOTAL_FIRES) AS total_fires,
        SUM(BUILDING_FIRES) AS building_fires, SUM(PROPERTY_DAMAGE_KRW) AS total_damage,
        ROUND(
            LEAST(SUM(BUILDING_FIRES)::FLOAT / NULLIF(SUM(TOTAL_FIRES), 0) * 35, 35)
            + LEAST(SUM(TOTAL_FIRES) / 300.0 * 35, 35)
            + LEAST(SUM(PROPERTY_DAMAGE_KRW) / 8000000000.0 * 30, 30)
        , 1) AS FIRE_RISK_SCORE
    FROM INSURE_DB.STAGING.STG_FIRE_STATS GROUP BY DISTRICT_NAME, YEAR
),
crime_risk AS (
    SELECT DISTRICT_NAME, YEAR, THEFT, BURGLARY, TOTAL_CRIMES,
        ROUND(LEAST(THEFT / 6000.0 * 50, 50) + LEAST(BURGLARY / 600.0 * 30, 30)
            + LEAST(TOTAL_CRIMES / 15000.0 * 20, 20), 1) AS THEFT_RISK_SCORE
    FROM INSURE_DB.STAGING.STG_CRIME_STATS
),
building_risk AS (
    SELECT DISTRICT_NAME, YEAR, AVG_BUILDING_AGE,
        ROUND(LEAST(AVG_BUILDING_AGE / 40.0 * 40, 40)
            + CASE WHEN AGE_OVER_40Y > 0 THEN LEAST(AGE_OVER_40Y::FLOAT / NULLIF(TOTAL_BUILDINGS, 0) * 100 * 30, 30) ELSE 0 END
            + CASE WHEN WOODEN_BUILDINGS > 0 THEN LEAST(WOODEN_BUILDINGS::FLOAT / NULLIF(TOTAL_BUILDINGS, 0) * 100 * 30, 30) ELSE 0 END
        , 1) AS BUILDING_RISK_SCORE
    FROM INSURE_DB.STAGING.STG_BUILDING_AGE
),
weather_risk_agg AS (
    SELECT DISTRICT_NAME, LEFT(YEAR_MONTH, 4)::INT AS YEAR,
        ROUND(AVG(FLOOD_RISK_SCORE) * 0.6 + AVG(WIND_RISK_SCORE) * 0.4, 1) AS WEATHER_RISK_SCORE
    FROM INSURE_DB.STAGING.STG_WEATHER_RISK GROUP BY DISTRICT_NAME, LEFT(YEAR_MONTH, 4)::INT
),
safety_score AS (
    SELECT DISTRICT_NAME, YEAR,
        ROUND(FIRE_SAFETY_SCORE * 0.5 + LEAST(FIRE_HYDRANTS / 600.0 * 25, 25)
            + LEAST(FIREFIGHTERS / 350.0 * 25, 25), 1) AS SAFETY_INFRA_SCORE
    FROM INSURE_DB.STAGING.STG_FIRE_FACILITY
),
cctv_score AS (
    SELECT DISTRICT_NAME, YEAR, CCTV_PER_1000_PEOPLE,
        ROUND(LEAST(CCTV_PER_1000_PEOPLE / 10.0 * 100, 100), 1) AS CCTV_SECURITY_SCORE
    FROM INSURE_DB.STAGING.STG_CCTV
)
SELECT f.DISTRICT_NAME, f.YEAR,
    f.FIRE_RISK_SCORE, c.THEFT_RISK_SCORE, b.BUILDING_RISK_SCORE, w.WEATHER_RISK_SCORE,
    s.SAFETY_INFRA_SCORE, cc.CCTV_SECURITY_SCORE,
    -- v1.1: 화재/도난 가중치 상향 (동산보험 특성 반영)
    ROUND(f.FIRE_RISK_SCORE * 0.30 + COALESCE(c.THEFT_RISK_SCORE, 0) * 0.30
        + COALESCE(b.BUILDING_RISK_SCORE, 0) * 0.15 + COALESCE(w.WEATHER_RISK_SCORE, 0) * 0.10
        - COALESCE(s.SAFETY_INFRA_SCORE, 0) * 0.08 - COALESCE(cc.CCTV_SECURITY_SCORE, 0) * 0.07
    , 1) AS COMPOSITE_RISK_SCORE,
    CASE
        WHEN (f.FIRE_RISK_SCORE * 0.30 + COALESCE(c.THEFT_RISK_SCORE, 0) * 0.30
              + COALESCE(b.BUILDING_RISK_SCORE, 0) * 0.15 + COALESCE(w.WEATHER_RISK_SCORE, 0) * 0.10
              - COALESCE(s.SAFETY_INFRA_SCORE, 0) * 0.08 - COALESCE(cc.CCTV_SECURITY_SCORE, 0) * 0.07) >= 50 THEN '고위험'
        WHEN (f.FIRE_RISK_SCORE * 0.30 + COALESCE(c.THEFT_RISK_SCORE, 0) * 0.30
              + COALESCE(b.BUILDING_RISK_SCORE, 0) * 0.15 + COALESCE(w.WEATHER_RISK_SCORE, 0) * 0.10
              - COALESCE(s.SAFETY_INFRA_SCORE, 0) * 0.08 - COALESCE(cc.CCTV_SECURITY_SCORE, 0) * 0.07) >= 30 THEN '중위험'
        ELSE '저위험'
    END AS RISK_GRADE
FROM fire_risk f
LEFT JOIN crime_risk c ON f.DISTRICT_NAME = c.DISTRICT_NAME AND f.YEAR = c.YEAR
LEFT JOIN building_risk b ON f.DISTRICT_NAME = b.DISTRICT_NAME AND f.YEAR = b.YEAR
LEFT JOIN weather_risk_agg w ON f.DISTRICT_NAME = w.DISTRICT_NAME AND f.YEAR = w.YEAR
LEFT JOIN safety_score s ON f.DISTRICT_NAME = s.DISTRICT_NAME AND f.YEAR = s.YEAR
LEFT JOIN cctv_score cc ON f.DISTRICT_NAME = cc.DISTRICT_NAME AND f.YEAR = cc.YEAR;

-- Step 2: Rebuild MART with 25-gu coverage (3 real + 22 estimated)
USE SCHEMA MART;

CREATE OR REPLACE TABLE MART_DISTRICT_INSURANCE_SUMMARY AS
WITH
real_data AS (
    SELECT m.DISTRICT_CODE, dm.DISTRICT_KOR_NAME AS DISTRICT_NAME,
        COALESCE(g.GU_NAME, dm.CITY_KOR_NAME) AS GU_NAME, m.YEAR_MONTH,
        COUNT(DISTINCT m.COMPOSITE_SEGMENT) AS ACTIVE_SEGMENTS,
        SUM(m.POPULATION) AS TOTAL_POPULATION,
        AVG(m.AVG_INCOME) AS DISTRICT_AVG_INCOME, AVG(m.AVG_ASSET) AS DISTRICT_AVG_ASSET,
        AVG(m.ESTIMATED_MOVABLE_ASSET_VALUE) AS AVG_MOVABLE_ASSET,
        AVG(m.BASE_PREMIUM_MONTHLY) AS AVG_BASE_PREMIUM, AVG(m.AVG_CREDIT) AS AVG_CREDIT_SCORE
    FROM INSURE_DB.MART.MART_INSURANCE_DESIGN m
    LEFT JOIN INSURE_DB.STAGING.STG_DISTRICT_MASTER dm ON m.DISTRICT_CODE = dm.DISTRICT_CODE
    LEFT JOIN INSURE_DB.STAGING.GU_CODE_MAPPING g ON LEFT(m.DISTRICT_CODE::VARCHAR, 5) = g.GU_CODE
    GROUP BY m.DISTRICT_CODE, dm.DISTRICT_KOR_NAME, COALESCE(g.GU_NAME, dm.CITY_KOR_NAME), m.YEAR_MONTH
),
seoul_avg AS (
    SELECT AVG(DISTRICT_AVG_INCOME) AS avg_income, AVG(DISTRICT_AVG_ASSET) AS avg_asset,
        AVG(AVG_MOVABLE_ASSET) AS avg_movable, AVG(AVG_BASE_PREMIUM) AS avg_premium,
        AVG(AVG_CREDIT_SCORE) AS avg_credit
    FROM real_data
),
covered_gu AS (SELECT DISTINCT GU_NAME FROM real_data WHERE GU_NAME IS NOT NULL),
missing_gu AS (
    SELECT g.GU_NAME, '202512' AS YEAR_MONTH
    FROM INSURE_DB.STAGING.GU_CODE_MAPPING g
    WHERE g.GU_NAME NOT IN (SELECT GU_NAME FROM covered_gu)
),
estimated_pop AS (
    SELECT dm.CITY_KOR_NAME AS GU_NAME, COUNT(DISTINCT dm.DISTRICT_CODE) * 8500 AS EST_POPULATION
    FROM INSURE_DB.STAGING.STG_DISTRICT_MASTER dm
    WHERE dm.PROVINCE_KOR_NAME = '서울특별시' GROUP BY dm.CITY_KOR_NAME
),
estimated_data AS (
    SELECT NULL AS DISTRICT_CODE, mg.GU_NAME AS DISTRICT_NAME, mg.GU_NAME, mg.YEAR_MONTH,
        5 AS ACTIVE_SEGMENTS, COALESCE(ep.EST_POPULATION, 80000) AS TOTAL_POPULATION,
        sa.avg_income AS DISTRICT_AVG_INCOME, sa.avg_asset AS DISTRICT_AVG_ASSET,
        sa.avg_movable AS AVG_MOVABLE_ASSET, sa.avg_premium AS AVG_BASE_PREMIUM,
        sa.avg_credit AS AVG_CREDIT_SCORE
    FROM missing_gu mg CROSS JOIN seoul_avg sa
    LEFT JOIN estimated_pop ep ON mg.GU_NAME = ep.GU_NAME
),
all_districts AS (
    SELECT * FROM real_data WHERE GU_NAME IS NOT NULL
    UNION ALL SELECT * FROM estimated_data
),
risk AS (
    SELECT DISTRICT_NAME, YEAR, COMPOSITE_RISK_SCORE, RISK_GRADE,
           FIRE_RISK_SCORE, THEFT_RISK_SCORE, BUILDING_RISK_SCORE, WEATHER_RISK_SCORE
    FROM INSURE_DB.INTERMEDIATE.INT_DISTRICT_RISK_SCORE
)
SELECT d.DISTRICT_CODE, d.DISTRICT_NAME, d.GU_NAME, d.YEAR_MONTH,
    d.ACTIVE_SEGMENTS, d.TOTAL_POPULATION,
    d.DISTRICT_AVG_INCOME, d.DISTRICT_AVG_ASSET,
    d.AVG_MOVABLE_ASSET, d.AVG_BASE_PREMIUM, d.AVG_CREDIT_SCORE,
    COALESCE(r.COMPOSITE_RISK_SCORE, 30) AS COMPOSITE_RISK_SCORE,
    COALESCE(r.RISK_GRADE, '미산정') AS RISK_GRADE,
    COALESCE(r.FIRE_RISK_SCORE, 0) AS FIRE_RISK_SCORE,
    COALESCE(r.THEFT_RISK_SCORE, 0) AS THEFT_RISK_SCORE,
    COALESCE(r.BUILDING_RISK_SCORE, 0) AS BUILDING_RISK_SCORE,
    COALESCE(r.WEATHER_RISK_SCORE, 0) AS WEATHER_RISK_SCORE,
    ROUND(d.AVG_BASE_PREMIUM * (1 + COALESCE(r.COMPOSITE_RISK_SCORE, 30) / 200.0)
        * CASE WHEN d.AVG_CREDIT_SCORE >= 800 THEN 0.90
               WHEN d.AVG_CREDIT_SCORE >= 700 THEN 0.95
               ELSE 1.05 END, 0) AS ADJUSTED_PREMIUM_MONTHLY,
    ROUND(d.TOTAL_POPULATION * 0.15 * d.AVG_BASE_PREMIUM * 12, 0) AS ESTIMATED_ANNUAL_MARKET_KRW
FROM all_districts d
LEFT JOIN risk r ON d.GU_NAME = r.DISTRICT_NAME AND LEFT(d.YEAR_MONTH, 4)::INT = r.YEAR
WHERE d.GU_NAME IS NOT NULL;

-- Step 3: Recreate view
CREATE OR REPLACE VIEW MART_PREMIUM_SIMULATION AS
SELECT d.*, ROUND(d.ADJUSTED_PREMIUM_MONTHLY * 0.5, 0) AS PREMIUM_50PCT,
       ROUND(d.ADJUSTED_PREMIUM_MONTHLY * 0.8, 0) AS PREMIUM_80PCT,
       d.ADJUSTED_PREMIUM_MONTHLY AS PREMIUM_100PCT,
       d.ADJUSTED_PREMIUM_MONTHLY * 12 AS ANNUAL_PREMIUM
FROM MART_DISTRICT_INSURANCE_SUMMARY d WHERE d.YEAR_MONTH IS NOT NULL;

